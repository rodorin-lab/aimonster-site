// Isolated real Chromium, actual production build. Does NOT start checkout.
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const {spawn} = require('node:child_process');
const base = process.env.FACTORY_TEST_URL || 'http://127.0.0.1:6179';
const delay = ms => new Promise(r=>setTimeout(r,ms));
async function main() {
  const profile = fs.mkdtempSync(path.join(os.tmpdir(),'mf2-browser-'));
  const chrome = spawn(process.env.CHROME_BIN || '/home/rodorin/.local/bin/google-chrome',['--headless=new','--no-first-run','--no-default-browser-check','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader','--remote-debugging-port=0',`--user-data-dir=${profile}`,'about:blank'],{stdio:['ignore','ignore','pipe']});
  let ws;
  try {
    const endpoint = await new Promise((resolve,reject)=>{
      let log='';const timer=setTimeout(()=>reject(Error(log.slice(-1000))),15000);
      chrome.stderr.on('data',b=>{log+=b;const m=log.match(/DevTools listening on (ws:\/\/\S+)/);if(m){clearTimeout(timer);resolve(m[1]);}});
      chrome.on('error',reject);
    });
    const pages=await (await fetch(endpoint.replace('ws:','http:').split('/devtools/')[0]+'/json')).json();
    ws=new WebSocket(pages.find(p=>p.type==='page').webSocketDebuggerUrl);
    await new Promise(r=>ws.onopen=r);
    let id=0;const pending=new Map(), exceptions=[], failedRequests=[], logs=[];
    ws.onmessage=({data})=>{const m=JSON.parse(data);if(m.id){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(Error(JSON.stringify(m.error))):p.resolve(m.result);}if(m.method==='Runtime.exceptionThrown')exceptions.push(m.params.exceptionDetails);if(m.method==='Network.responseReceived'&&m.params.response.status>=400)failedRequests.push(m.params.response.url);if(m.method==='Runtime.consoleAPICalled'&&m.params.type==='error')logs.push(m.params.args.map(a=>a.value||a.description).join(' '));};
    const send=(method,params={})=>new Promise((resolve,reject)=>{const n=++id;pending.set(n,{resolve,reject});ws.send(JSON.stringify({id:n,method,params}));});
    const ev=async expression=>{const r=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
    const wait=async(expression,message,timeout=15000)=>{const start=Date.now();while(Date.now()-start<timeout){if(await ev(`Boolean(${expression})`))return;await delay(80);}throw Error('timeout: '+message);};
    await send('Runtime.enable');await send('Network.enable');await send('Page.enable');
    await send('Page.addScriptToEvaluateOnNewDocument',{source:"localStorage.setItem('dll-lang','en')"});
    await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
    await send('Page.navigate',{url:base});
    await wait('document.querySelectorAll("#market article").length===7','seven products');
    await wait(`document.querySelector('button[aria-label="Save this creature to field notes"]')?.disabled === false`,'hydration');
    console.log('PASS: production home renders all 7 original products');
    const clickText=async text=>ev(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(text)});if(!b)throw Error('button not found');b.click();return true})()`);
    await clickText('With 3D prototype');
    await wait('document.querySelectorAll("#market article").length===1','3D filter');
    assert.match(await ev('document.querySelector("#market article").textContent'),/FIRE DRAGON PACK/);
    await clickText('All specimens');
    await wait('document.querySelectorAll("#market article").length===7','reset filter');
    await ev(`(()=>{const input=document.querySelector('input[type=search]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'zz-nothing-zz');input.dispatchEvent(new Event('input',{bubbles:true}));})()`);
    await wait('document.querySelectorAll("#market article").length===0','search empty state');
    await clickText('Show all packs');
    await wait('document.querySelectorAll("#market article").length===7','empty-state reset');
    await ev(`(()=>{const el=document.querySelector('select');Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(el,'high');el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
    await wait('document.querySelector("#market article").textContent.includes("HOLY DRAGON PACK")','price ordering');
    console.log('PASS: 3D filter, search/empty/reset and price sort');
    await ev(`document.querySelector('button[aria-label="Save this creature to field notes"]').click()`);
    await wait('document.querySelectorAll("#fieldnotes article").length===1','save');
    await send('Page.reload');
    await wait('document.querySelectorAll("#fieldnotes article").length===1','saved after reload');
    assert.equal(await ev('JSON.parse(localStorage.getItem("mf2-field-notes-v1"))[0]'),'fire-dragon');
    await ev(`document.querySelector('button[aria-label="Ice Dragon"]').click()`);
    await wait('!document.querySelector("button[aria-pressed=false]")?.textContent.includes("EXPLORE IN 3D")','specimen change');
    assert.equal(await ev('[...document.querySelectorAll("button")].some(b=>b.textContent.includes("EXPLORE IN 3D"))'),false);
    await ev(`document.querySelector('button[aria-label="Fire Dragon"]').click()`);
    await ev(`document.querySelector('button[aria-label="CREATURE STARTER PACK compare"]').click()`);
    await wait('document.querySelectorAll("table tbody tr").length===1','compare');
    console.log('PASS: persistent field notes, honest 3D availability, comparison');
    await ev(`[...document.querySelectorAll('button')].find(b=>b.textContent.includes('EXPLORE IN 3D')).click()`);
    await wait('document.querySelector("#observatory canvas")','real GLB canvas',20000);
    await delay(1500);
    await clickText('↶ PIXEL');
    console.log('PASS: existing Fire Dragon 3D viewer loads and returns to pixel');
    await clickText('▷ Begin experiment');
    await wait('document.querySelector("#playground canvas")','3D game canvas',20000);
    await clickText('Start round');
    await wait('!document.body.textContent.includes("MEET YOUR RESONANCE")','round started');
    const move=async(key,code,ms)=>{await send('Input.dispatchKeyEvent',{type:'keyDown',key,code});await delay(ms);await send('Input.dispatchKeyEvent',{type:'keyUp',key,code});};
    await move('ArrowUp','ArrowUp',900);
    await wait('document.querySelector("[data-testid=game-score]").textContent.includes("1 / 6")','actual keyboard movement collects a crystal');
    await clickText('Pause');
    await wait('document.body.textContent.includes("WORLD ON HOLD")','pause');
    const frozen=await ev('document.querySelector("[data-testid=game-time]").textContent');await delay(1200);
    assert.equal(await ev('document.querySelector("[data-testid=game-time]").textContent'),frozen);
    await clickText('Resume');await delay(300);
    await send('Runtime.evaluate',{expression:'window.dispatchEvent(new Event("blur"))'});
    await wait('document.body.textContent.includes("WORLD ON HOLD")','auto-pause');
    console.log('PASS: real 3D keyboard play collects crystal, pause freezes timer, blur auto-pauses');
    fs.mkdirSync('test-artifacts',{recursive:true});
    await send('Runtime.evaluate',{expression:'window.scrollTo(0,0)'});
    const desktop=await send('Page.captureScreenshot',{format:'png'});
    fs.writeFileSync('test-artifacts/desktop.png',Buffer.from(desktop.data,'base64'));
    await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
    await delay(200);
    assert.ok(await ev('document.documentElement.scrollWidth<=390'),'mobile has no horizontal overflow');
    const mobile=await send('Page.captureScreenshot',{format:'png'});
    fs.writeFileSync('test-artifacts/mobile.png',Buffer.from(mobile.data,'base64'));
    await ev(`document.querySelector('button[aria-label="Switch to Japanese"]').click()`);
    await wait('document.querySelector("h1").textContent.includes("出会いから")','Japanese');
    console.log('PASS: 390px mobile layout and Japanese language switch');
    for(const route of ['/classic','/packs/creature-starter-pack','/packs/fire-dragon-pack','/packs/ice-dragon-pack','/packs/electric-slime-pack','/packs/dark-dragon-pack','/packs/lava-slime-pack','/packs/holy-dragon-pack','/creatures/fire-dragon','/monsters/3d/monster.glb']) {
      const res=await fetch(base+route);assert.equal(res.status,200,route);await res.arrayBuffer();
    }
    console.log('PASS: classic, all 7 product pages, creature route and GLB return 200');
    assert.deepEqual(exceptions,[],'no uncaught browser exceptions');
    assert.deepEqual(failedRequests,[],'no failed HTTP responses');
    assert.deepEqual(logs,[],'no browser console errors');
    console.log('PASS: no browser exceptions, console errors or failed requests');
  } finally { ws?.close();chrome.kill(); }
}
main().catch(err=>{console.error(err);process.exitCode=1;});
